#!/usr/bin/env python3
"""Writes examples_v1_3_0.py (a NEW file; examples_v1_2_0.py and examples_out_v1_2_0.json stay): the executed rows of the 27 code slides of the deck v3.7.0 as the deck check v1.2.0 needs them recorded.
One group per code slide, 'SlideNN': the slide's listing (its code boxes joined by line breaks, run as one statement) and the expression of its result line. The PRELUDE and every earlier group are those of v1_2_0.
Usage: deck_examples_make_v1_3_0.py DECK.pptx"""
import os, sys, zipfile
from xml.dom import minidom
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, ".."))
import sen0401_code_marker_v1_0_0 as MARK
z = zipfile.ZipFile(sys.argv[1]); out = []
for n in range(1, 69):
    listing, rows = MARK.form2(MARK.xml_shapes(minidom.parseString(z.read("ppt/slides/slide%d.xml" % n))))
    if rows:
        assert len(rows) == 1; out.append((n, listing, rows[0][0]))
body = '"""Executed rows of the chapter 5 deck v3.7.0 code slides (generated by deck_examples_make_v1_3_0.py from the deck): every group of examples_v1_2_0.py plus one group per code slide, the slide listing\nand the expression of its result line. PRELUDE is that of v1_2_0."""\n__version__ = "1.3.0"\nimport os, sys\nsys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))\nfrom examples_v1_2_0 import EX as _EX, PRELUDE\nEX = dict(_EX)\n'
for n, l, e in out: body += "EX[%r] = [%r, %r]\n" % ("Slide%02d" % n, l, e)
open(os.path.join(HERE, "examples_v1_3_0.py"), "w", encoding="utf-8").write(body); print("written examples_v1_3_0.py,", len(out), "slide groups")
